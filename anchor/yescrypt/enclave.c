static int run_one_kdf(const struct kat *k)
{
    yescrypt_local_t local;
    yescrypt_params_t params;
    uint8_t dk[64];
    size_t plen;
    size_t slen;

    if (k->dklen > sizeof(dk))
        return -1;

    if (yescrypt_init_local(&local))
        return -1;

    params.flags = k->flags;
    params.N = k->N;
    params.r = k->r;
    params.p = k->p;
    params.t = k->t;
    params.g = k->g;
    params.NROM = 0;

    plen = k->passwd ? strlen(k->passwd) : 0;
    slen = k->salt ? strlen(k->salt) : 0;

    int kdf_status = yescrypt_kdf(NULL, &local, (const uint8_t *)k->passwd,
                                  plen, (const uint8_t *)k->salt, slen, &params,
                                  dk, k->dklen);
    int free_status = yescrypt_free_local(&local);
    if (kdf_status != 0 || free_status != 0)
        return -1;
    if (memcmp(dk, k->expect, k->dklen) != 0)
        return -1;
    return 0;
}

static int run_scrypt_kat(void)
{
    uint8_t dk[64];

    if (crypto_scrypt((const uint8_t *)"", 0, (const uint8_t *)"", 0, 16, 1, 1,
                      dk, sizeof(dk)))
        return -1;
    if (memcmp(dk, expect_scrypt_empty, sizeof(expect_scrypt_empty)) != 0)
        return -1;
    return 0;
}

int ecall_yescrypt_selftest(void)
{
    static const struct kat kats[] = {
        /* Covers pwxform via YESCRYPT_DEFAULTS. */
        {"", "", YESCRYPT_DEFAULTS, 4, 1, 1, 0, 0, 64, expect_defaults_empty},
        {"p", "s", YESCRYPT_DEFAULTS, 16, 8, 1, 0, 0, 40, expect_defaults_ps},
        /* Cross-checks the non-pwxform WORM path. */
        {"", "", YESCRYPT_WORM, 4, 1, 1, 0, 0, 64, expect_worm_empty},
    };
    int failures = 0;
    size_t i;

    for (i = 0; i < sizeof(kats) / sizeof(kats[0]); i++) {
        if (run_one_kdf(&kats[i]) != 0)
            failures++;
    }
    if (run_scrypt_kat() != 0)
        failures++;

    return failures;
}
